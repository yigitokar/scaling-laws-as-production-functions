def _design(d, xs, fe):
    X = d[xs].astype(float).copy()
    if fe is not None:
        X = pd.concat([X, ob._dummies(d, fe)], axis=1)
    return sm.add_constant(X, has_constant="add")


def _cr1(X, u, g):
    """OLS coefficients' CR1 covariance (statsmodels' default small-sample correction)."""
    n, k = X.shape
    XtXi = np.linalg.pinv(X.T @ X)
    G = len(np.unique(g))
    meat = np.zeros((k, k))
    for c in np.unique(g):
        s = X[g == c].T @ u[g == c]
        meat += np.outer(s, s)
    return (G / (G - 1)) * ((n - 1) / (n - k)) * XtXi @ meat @ XtXi


def wild_cluster_test(d, yname, xs, fe, par, theta0, B=999, seed=0):
    """Restricted wild cluster bootstrap-t (Webb six-point weights; cameron2008bootstrap, webb2023reworking) of
    H0: coef[par] = theta0 with developer clusters. Used to check the few-cluster (G~19) CR1 inference on the
    Table 6 biases, treating the experimental benchmark as fixed (its bootstrap SE is small by comparison)."""
    rng = np.random.default_rng(seed)
    X = _design(d, xs, fe)
    cols = list(X.columns)
    j = cols.index(par)
    Xv, y = X.values, d[yname].values.astype(float)
    g = pd.factorize(d.developer)[0]
    b = np.linalg.lstsq(Xv, y, rcond=None)[0]
    u = y - Xv @ b
    t_obs = (b[j] - theta0) / np.sqrt(_cr1(Xv, u, g)[j, j])
    # restricted fit: impose coef[par] = theta0
    Xr = np.delete(Xv, j, axis=1)
    yr = y - theta0 * Xv[:, j]
    br = np.linalg.lstsq(Xr, yr, rcond=None)[0]
    fit_r, ur = Xr @ br + theta0 * Xv[:, j], yr - Xr @ br
    webb = np.array([-np.sqrt(1.5), -1.0, -np.sqrt(0.5), np.sqrt(0.5), 1.0, np.sqrt(1.5)])
    G = g.max() + 1
    ts = np.empty(B)
    for i in range(B):
        w = rng.choice(webb, G)[g]
        ys = fit_r + w * ur
        bs = np.linalg.lstsq(Xv, ys, rcond=None)[0]
        us = ys - Xv @ bs
        ts[i] = (bs[j] - theta0) / np.sqrt(_cr1(Xv, us, g)[j, j])
    return dict(t_cr1=float(t_obs), p_cr1_normal=float(2 * (1 - __import__("scipy").stats.norm.cdf(abs(t_obs)))),
                p_wild=float(np.mean(np.abs(ts) >= abs(t_obs))), n_clusters=int(G), B=B)


def wild_bias_table(res, hull_obs, out, fname, B=999, seed=0):
    """Wild-cluster p-values for H0: bias = 0 (obs estimator = experimental benchmark) for the Table 6 rows."""
    d = hull_obs.copy()
    d["devyear"] = d.developer + "_" + d.year.astype(str)
    rows = []
    for est, fe in [("OLS", None), ("Year FE", "year"), ("Developer FE", "developer"), ("Family FE", "family"),
                    ("Lab x period FE", "devyear")]:
        for par, xs, col in [("theta_N", ["n", "d"], "n"), ("theta_D", ["n", "d"], "d"), ("theta_C", ["c"], "c")]:
            r = res[(res.estimator == est) & (res.param == par)]
            if not len(r):
                continue
            th0 = float(r.bench.iloc[0])
            w = wild_cluster_test(d, out, xs, fe, col, th0, B=B, seed=seed)
            rows.append(dict(estimator=est, param=par, obs=float(r.obs.iloc[0]), bench=th0, bias=float(r.bias.iloc[0]),
                             bias_se=float(r.bias_se.iloc[0]), **w))
    W = pd.DataFrame(rows)
    W.to_csv(os.path.join(TABDIR, f"{PREFIX}_{fname}_wildboot.csv"), index=False)
    return W
